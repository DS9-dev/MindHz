/**
 * Frequency catalogue.
 *
 * Three different quantities are kept apart on purpose:
 *  - 'audible' — the frequency of a sound you hear (a tone, Hz);
 *  - 'rhythm'  — the rate of beats / pulses / modulation applied to an audible
 *                carrier (Hz); you hear it as a rhythm, not as a pitch;
 *  - 'brain'   — an EEG frequency band of electrical brain activity that a state is
 *                *associated* with. Listening to a rhythm in that band is NOT the
 *                same as the brain being in that state.
 *
 * Evidence levels describe the main *claimed effect* of an entry, not the
 * existence of the frequency itself.
 */
import type { BandId } from '../audio/validate';
import type { EvidenceLevel, Layer, LayerKind, NoiseColor } from '../types';

export type CatalogCategory = 'brainwave' | 'acoustic' | 'solfeggio' | 'esoteric' | 'noise' | 'custom';
export type Quantity = 'audible' | 'rhythm' | 'brain' | 'noise';

export interface PlaySpec {
  kind: LayerKind;
  carrierHz?: number;
  beatHz?: number;
  depth?: number;
  noiseColor?: NoiseColor;
  volume?: number;
}

export interface CatalogEntry {
  id: string;
  name: string;
  category: CatalogCategory;
  quantity: Quantity;
  /** Single value in Hz (null for noise). */
  value: number | null;
  /** Range in Hz for bands. */
  range?: [number, number];
  band?: BandId;
  summary: string;
  /** Intended / associated use — never a promise. */
  purpose: string;
  science: string;
  esoteric?: string;
  evidence: EvidenceLevel;
  limitations: string;
  refs: string[];
  play: PlaySpec[];
  tags: string[];
}

const BIN = (beat: number, carrier = 200): PlaySpec[] => [{ kind: 'binaural', carrierHz: carrier, beatHz: beat }];
const ISO = (beat: number, carrier = 300): PlaySpec[] => [{ kind: 'isochronic', carrierHz: carrier, beatHz: beat, depth: 1 }];
const TONE = (hz: number): PlaySpec[] => [{ kind: 'tone', carrierHz: hz, volume: 0.5 }];

