  'Регистрируемая реакция мозга на ритм звука не равна изменению состояния или улучшению функций.';

const SOLFEGGIO_SCIENCE =
  'Это обычный слышимый тон. Научных исследований, показывающих особые свойства именно этого значения частоты, нет. ' +
  'Исторические слоги сольфеджио (Ut, Re, Mi, Fa, Sol, La — гимн «Ut queant laxis», XI в.) обозначали ступени звукоряда, ' +
  'а не фиксированные частоты: стандартной высоты строя в то время не существовало. Набор «частот сольфеджио» ' +
  'популяризирован в конце XX века (Horowitz & Puleo, 1999) и получен нумерологическими преобразованиями.';

const SOLFEGGIO_LIMITS =
  'Заявленные эффекты не подтверждены. Любое ощущение после прослушивания может объясняться ожиданием, ' +
  'расслабляющей обстановкой и самим фактом паузы.';

function solfeggio(hz: number, syllable: string, esoteric: string, extra: Partial<CatalogEntry> = {}): CatalogEntry {
  return {
    id: `solf-${hz}`,
    name: `${hz} Гц — ${syllable}`,
    category: 'solfeggio',
    quantity: 'audible',
    value: hz,
    summary: `Тон ${hz} Гц из популярной системы «частот сольфеджио».`,
    purpose: 'Используется в звуковых медитациях и духовных практиках.',
    science: SOLFEGGIO_SCIENCE,
    esoteric,
    evidence: 'esoteric',
    limitations: SOLFEGGIO_LIMITS,
    refs: ['horowitz1999'],
    play: TONE(hz),
    tags: ['сольфеджио', 'медитация', String(hz)],
    ...extra,
  };
}

